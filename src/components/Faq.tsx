"use client";
import { useState } from "react";

const items = [
  ["Почему вода стоит после дождя?", "Чаще всего причина в сочетании глинистого грунта, понижения рельефа и отсутствия организованного отвода. На осмотре инженер определяет, откуда приходит вода и где ей безопасно уходить."],
  ["Чем поверхностный дренаж отличается от глубинного?", "Поверхностный контур собирает дождевую и талую воду. Глубинный работает с водой в грунте и защищает фундамент. На сложных участках применяют оба контура в одной схеме."],
  ["Куда можно отвести воду?", "В зависимости от рельефа: придорожная канава, действующая ливневая сеть, поглотительный колодец или герметичный колодец с насосом. Точка сброса определяется на замере и фиксируется в проекте."],
  ["Можно ли смонтировать дренаж у готового дома?", "Да. Трассу подбирают с учётом фундамента, отмостки, дорожек и существующего благоустройства. В смете отдельно фиксируем восстановление поверхности после работ."],
  ["Почему нельзя считать дренаж только по площади?", "Стоимость зависит от погонажа, глубины, типа грунта, количества колодцев, перепада высот и способа сброса. Площадь помогает понять масштаб, но не заменяет схему."],
  ["Сколько времени занимает монтаж?", "Типовой объём — 3–7 рабочих дней. Точный срок зависит от длины трассы, погоды и объёма земляных работ. Срок фиксируется в договоре."],
];

export function Faq() {
  const [open, setOpen] = useState(0);
  return (
    <div className="faq-list">
      {items.map(([question, answer], i) => (
        <div className={open === i ? "faq open" : "faq"} key={question}>
          <button onClick={() => setOpen(open === i ? -1 : i)} aria-expanded={open === i}>
            <span>{question}</span>
            <b>+</b>
          </button>
          {open === i && <p>{answer}</p>}
        </div>
      ))}
    </div>
  );
}
